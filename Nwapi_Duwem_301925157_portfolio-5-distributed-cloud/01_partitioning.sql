-- Portfolio 5: range partitioning of orders by date.
DROP TABLE IF EXISTS orders_p;

CREATE TABLE orders_p (LIKE orders INCLUDING DEFAULTS) PARTITION BY RANGE (order_date);

CREATE TABLE orders_p_2024q4 PARTITION OF orders_p FOR VALUES FROM ('2024-10-01') TO ('2025-01-01');
CREATE TABLE orders_p_2025q1 PARTITION OF orders_p FOR VALUES FROM ('2025-01-01') TO ('2025-04-01');
CREATE TABLE orders_p_2025q2 PARTITION OF orders_p FOR VALUES FROM ('2025-04-01') TO ('2025-07-01');
CREATE TABLE orders_p_2025q3 PARTITION OF orders_p FOR VALUES FROM ('2025-07-01') TO ('2025-10-01');
CREATE TABLE orders_p_2025q4 PARTITION OF orders_p FOR VALUES FROM ('2025-10-01') TO ('2026-01-01');
CREATE TABLE orders_p_2026q1 PARTITION OF orders_p FOR VALUES FROM ('2026-01-01') TO ('2026-04-01');
CREATE TABLE orders_p_2026q2 PARTITION OF orders_p FOR VALUES FROM ('2026-04-01') TO ('2026-07-01');
CREATE TABLE orders_p_2026q3 PARTITION OF orders_p FOR VALUES FROM ('2026-07-01') TO ('2026-10-01');
CREATE TABLE orders_p_2026q4 PARTITION OF orders_p FOR VALUES FROM ('2026-10-01') TO ('2027-01-01');
CREATE TABLE orders_p_default PARTITION OF orders_p DEFAULT;   -- safety net for dates outside the ranges

INSERT INTO orders_p SELECT * FROM orders;
ANALYZE orders_p;